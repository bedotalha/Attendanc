const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8');
const names=['countedSessions','studentsFor','studentsForSession','localDate','getStatus','reportRate','selectedReportSessions','reportStudentSummary'];
const helpers=names.map(name=>source.split(/\r?\n/).find(l=>l.trimStart().startsWith('function '+name+'('))).join('\n');
const start=source.indexOf('    function parseCsv('), end=source.indexOf('    function studentListFilename(',start);
assert.ok(start>=0&&end>start,'CSV import functions must be present');
const importer=source.slice(start,end);
const controls={'#studentCourse':{value:'a'},'#reportCourse':{value:'a'},'#reportFrom':{value:''},'#reportTo':{value:''},'#reportPeriod':{value:'all'},'#reportDailySession':{value:''},'#reportAbsenceFilter':{checked:false}};
const db={courses:[{id:'a',name:'Group A',code:'SAME'},{id:'b',name:'Group B',code:'SAME'}],students:[{id:'sa',courseId:'a',name:'Existing',number:'1'},{id:'sb',courseId:'b',name:'Other',number:'1'}],sessions:[{id:'xa',courseId:'a',active:false,startedAt:'2026-10-10T11:00:00',records:{sa:{status:'present'}}},{id:'xb',courseId:'b',active:false,startedAt:'2026-10-10T11:00:00',records:{sb:{status:'present'}}}]};
let serial=0,confirmImport;
controls['#saveModal']={disabled:false};
const ctx=vm.createContext({db,workspaceCourseId:'a',$:id=>controls[id],courseById:id=>db.courses.find(c=>c.id===id),uid:()=>String(++serial),alert:()=>{},addAudit:()=>{},escapeHtml:String,openModal:(_title,_content,confirm)=>{controls['#saveModal'].disabled=false;confirmImport=confirm},closeModal:()=>{confirmImport=undefined},saveDb:async()=>{},renderAll:()=>{},attendanceReviewPending:()=>false});
vm.runInContext(helpers+'\n'+importer,ctx);
async function run(){
  const snapshotB=JSON.stringify({student:db.students[1],session:db.sessions[1]});
  ctx.importCsvText('name,number\nDuplicate,1\nNew,2\nMatching,3');
  assert.equal(ctx.studentsFor('a').length,1,'Preview must not commit rows');
  await confirmImport();
  assert.deepEqual(ctx.studentsFor('a').map(student=>student.name),['Existing','New','Matching']);
  assert.equal(ctx.studentsFor('b').length,1);
  assert.equal(ctx.studentsForSession(db.sessions[0]).length,3);
  const report=ctx.reportStudentSummary();
  assert.equal(report.length,3);
  assert.equal(report[1].absent,1);
  assert.equal(report[2].absent,1);
  assert.equal(ctx.reportRate(report.flatMap(row=>row.entries)),33);
  assert.equal(JSON.stringify({student:db.students[1],session:db.sessions[1]}),snapshotB);
  ctx.workspaceCourseId='b';
  ctx.importCsvText('طالبة جديدة;00123');
  await confirmImport();
  assert.equal(ctx.studentsFor('b').length,2);
  assert.equal(ctx.studentsFor('b')[1].number,'00123');
  assert.equal(ctx.studentsFor('a').length,3);
  ctx.workspaceCourseId='';
  controls['#studentCourse'].value='';
  const before=db.students.length;
  ctx.importCsvText('name,number\nNo course,5');
  assert.equal(confirmImport,undefined);
  assert.equal(db.students.length,before);
  console.log('PASS CSV preview and confirmation, duplicates, headerless import, course isolation and reports.');
}
run().catch(error=>{console.error(error);process.exitCode=1});
